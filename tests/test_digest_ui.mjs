import assert from 'node:assert/strict';
import {digestSections,sourceDescriptor,eventFilterOptions,eventBucket} from '../web/src/feed.js';

const items=['results','management_change','litigation','fund_raise','M&A','price','volume'].map(category=>({category}));
assert.deepEqual(digestSections(items).events.map(i=>i.category),items.slice(0,5).map(i=>i.category));
assert.equal(digestSections(items,'market').events.length,0);
assert.equal(digestSections(items,'market').market.length,2);
assert.deepEqual(digestSections(items,'events','other').events,[]);
assert.deepEqual(digestSections(items,'events','risk').events.map(i=>i.category),['litigation']);
assert.deepEqual(digestSections(items,'events','mergers').events.map(i=>i.category),['M&A']);
assert.deepEqual(digestSections(items,'events','fund_raise').events.map(i=>i.category),['fund_raise']);
assert.equal(eventBucket({category:'capex'}),'capex');
assert.equal(eventBucket({category:'credit_rating'}),'risk');
assert.equal(eventBucket({category:'press_release'}),'other');
assert.equal(eventBucket({category:'dividend'}),'other');
assert.equal(eventFilterOptions(items).some(o=>o.key==='other'),false);
assert.equal(eventFilterOptions(items,'other').some(o=>o.key==='other'&&o.count===0),true);
assert.deepEqual(eventFilterOptions([]),[{key:'all',label:'All events',count:0}]);
assert.equal(digestSections(items,'events','results').events.length,1);
assert.equal(digestSections(items,'events','management_change').events.length,1);
assert.equal(digestSections(items,'events').market.length,0);
assert.deepEqual(digestSections([]),{events:[],market:[]});
assert.equal(sourceDescriptor('https://nsearchives.nseindia.com/filing.pdf').label,'NSE filing');
assert.equal(sourceDescriptor('https://www.bseindia.com/filing.pdf').label,'BSE filing');
assert.equal(sourceDescriptor('https://finance.yahoo.com/quote/INFY.NS/history/').label,'Yahoo EOD data');
assert.equal(sourceDescriptor('https://www.screener.in/company/INFY/').label,'Screener financials');
assert.equal(sourceDescriptor('https://nseindia.com.evil.example/').label,'Source document');
assert.equal(sourceDescriptor('javascript:alert(1)'),null);
assert.equal(sourceDescriptor('not a url'),null);
console.log('Digest groups, company-event filters and domain-based source attribution verified.');
